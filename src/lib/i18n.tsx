export type MessageKey = keyof typeof dictionary.es
export type Translator = (key: MessageKey, vars?: Record<string, string | number>) => string

interface I18nValue {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: Translator
}

const I18nContext = createContext<I18nValue | null>(null)

function readLocale(): Locale {
  try {
    return localStorage.getItem('lunilla.locale') === 'en' ? 'en' : 'es'
  } catch {
    return 'es'
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(readLocale)

  const setLocale = useCallback((next: Locale) => {
    try {
      localStorage.setItem('lunilla.locale', next)
    } catch {
      // The language still changes for this visit.
    }
    setLocaleState(next)
  }, [])

  useEffect(() => {
    document.documentElement.lang = locale
  }, [locale])

  const t = useCallback<Translator>((key, vars) => {
    const raw = dictionary[locale][key] ?? dictionary.es[key]
    if (!vars) return raw
    return raw.replace(/\{(\w+)\}/g, (_match, name: string) => String(vars[name] ?? ''))
  }, [locale])

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext)
  if (!value) throw new Error('i18n')
  return value
}
